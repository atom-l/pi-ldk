/**
 * model-attribution — per-turn model attribution in the LLM context.
 *
 * pi keeps one shared conversation when you switch models mid-session (`/model`),
 * but the context sent to the model carries no record of which model produced each
 * earlier response. This extension annotates the request context so the active
 * model can perceive the switch — and, crucially, does not mistake earlier turns
 * for its own:
 *
 *   - every earlier assistant response gets a bracketed tag inserted right after
 *     any leading thinking blocks. The tag is phrased in retrospect and names the
 *     relation to the answering model:
 *       [earlier response generated by a different model: provider/model — not you]
 *       [earlier response generated by your own model: provider/model]
 *       [earlier response generated by model: provider/model]        (current model unknown)
 *   - one harness note at the head of the conversation explains the convention;
 *     its text does not depend on the current model, so switching models keeps the
 *     cached prompt prefix intact.
 *   - when the history contains responses written by a different model than the
 *     one answering now, a short identity reminder is appended at the very end of
 *     the context (the highest-salience position right before generation):
 *     "you are X; the tags above name other models — not you".
 *   - a constant <model_attribution_policy> block is appended to the leading
 *     system message per request (context_with_system), because in-band notes alone
 *     are not enough to stop some models from echoing the tags.
 *   - echoed tags are stripped from finalized assistant messages (message_end) so
 *     imitation never pollutes the session transcript.
 *
 * The transformation is request-local (the `context` event runs before each LLM
 * call on a clone of the transcript): session files, the TUI transcript, exports,
 * and token accounting keep the original messages. Existing content blocks are
 * never modified — the tag is a new text block, so provider signatures
 * (`textSignature`, `thinkingSignature`, `thoughtSignature`) stay valid.
 *
 * Canonical source:  model-attribution/model-attribution.ts (this file)
 * Deployed copy:     <project>/.pi/extensions/model-attribution.ts
 * See README.md in the canonical directory for install/upgrade notes.
 */

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

/** Marker prefix shared by every variant. Also used for the idempotence check. */
export const MARKER_PREFIX = "[earlier response generated by ";
/** customType of the injected head note. */
export const NOTE_CUSTOM_TYPE = "model-attribution";
/** customType of the injected trailing identity reminder. */
export const REMINDER_CUSTOM_TYPE = "model-attribution-reminder";
/** Sentinel for the system-prompt policy block (idempotence check). */
export const POLICY_TAG = "<model_attribution_policy>";

/**
 * Leading attribution tags (current and legacy formats) a model may have echoed
 * into its own reply text.
 */
export const ECHO_TAG_LEADING_RE =
  /^(?:\[(?:earlier response generated by [^\]]*|response generated by model: [^\]]*)\]\s*)+/;

/** Permissive structural view of pi messages, so this file is testable standalone. */
export type MessageLike = {
  role: string;
  [key: string]: unknown;
};

type ContentBlock = { type: string; text?: unknown; [key: string]: unknown };

/** provider/model label for one assistant message, or null when it has no model metadata. */
export function modelLabelOf(message: MessageLike): string | null {
  const provider = message.provider;
  const model = message.model;
  if (typeof provider !== "string" || typeof model !== "string") return null;
  if (provider.length === 0 || model.length === 0) return null;
  let label = `${provider}/${model}`;
  const responseModel = message.responseModel;
  if (typeof responseModel === "string" && responseModel.length > 0 && responseModel !== model) {
    label += ` (served as ${responseModel})`;
  }
  return label;
}

/**
 * Build the marker for one assistant message.
 *
 * The wording is retrospective ("earlier response") and states the relation to the
 * model answering right now, so a marker inside a past assistant message cannot be
 * misread as the answering model's self-description.
 */
export function markerFor(message: MessageLike, currentModel?: string): string | null {
  const label = modelLabelOf(message);
  if (!label) return null;
  const provider = message.provider as string;
  const model = message.model as string;
  const base = `${provider}/${model}`;
  if (currentModel) {
    return base === currentModel
      ? `${MARKER_PREFIX}your own model: ${label}]`
      : `${MARKER_PREFIX}a different model: ${label} — not you]`;
  }
  return `${MARKER_PREFIX}model: ${label}]`;
}

/**
 * Insert the marker into one assistant message.
 *
 * The marker goes after any leading thinking blocks: Anthropic requires a thinking
 * block to stay first when replaying extended-thinking turns, and OpenAI Responses
 * pairs reasoning items with their function calls. A new text block is inserted
 * instead of editing an existing one so per-block provider signatures remain valid.
 * Returns the same object when the message is already annotated or has no metadata.
 */
export function annotateAssistantMessage(message: MessageLike, currentModel?: string): MessageLike {
  const marker = markerFor(message, currentModel);
  if (!marker) return message;
  const content = Array.isArray(message.content) ? (message.content as ContentBlock[]) : null;
  if (!content) return message;

  let index = 0;
  while (index < content.length && content[index]?.type === "thinking") index++;

  const at = content[index];
  if (at && at.type === "text" && typeof at.text === "string" && at.text.startsWith(MARKER_PREFIX)) {
    // Already annotated (e.g. this extension is loaded from two locations).
    return message;
  }

  return {
    ...message,
    content: [...content.slice(0, index), { type: "text", text: marker }, ...content.slice(index)],
  };
}

function customNote(customType: string, text: string, timestamp: number): MessageLike {
  return {
    role: "custom",
    customType,
    content: [{ type: "text", text }],
    display: false,
    timestamp,
  };
}

/**
 * Head note explaining the convention. Deliberately independent of the current
 * model so its position in the request never changes when models switch.
 */
export function buildNote(timestamp: number): MessageLike {
  const text =
    "<model_attribution>\n" +
    "This conversation may span multiple AI models. The agent harness inserts bracketed tags into past " +
    "assistant responses, such as " +
    `${MARKER_PREFIX}a different model: provider/model — not you] or ` +
    `${MARKER_PREFIX}your own model: provider/model]. ` +
    "Each tag is metadata recording which model wrote that earlier response; it is not text the assistant " +
    "wrote. Never reproduce such tags in your own replies, and never identify yourself with a model named in " +
    "a tag unless the tag explicitly says it is your own model.\n" +
    "</model_attribution>";
  return customNote(NOTE_CUSTOM_TYPE, text, timestamp);
}

/**
 * Trailing identity reminder, appended at the end of the context when the history
 * contains responses written by a model other than the one answering now. This is
 * the last thing the model reads before generating, which counters the tendency to
 * adopt the most recent tag as its own identity.
 */
export function buildReminder(currentModel: string, timestamp: number): MessageLike {
  const text =
    "<model_attribution_reminder>\n" +
    `Identity check before you answer: you are ${currentModel}, the model receiving this request right now. ` +
    "The bracketed " +
    `${MARKER_PREFIX}...] tags inside the assistant messages above are harness metadata naming the model ` +
    "that wrote each earlier response. A tag that reads \"a different model ... — not you\" was written by " +
    "another model: that response is not your own earlier reply, and you must not identify yourself with the " +
    "model it names. The transcript is shared across models; continue the work and answer the user's request. " +
    "When writing your reply: never reproduce these bracketed tags (or similar attribution tags) in your own " +
    "text — they are harness metadata, and echoing them corrupts the transcript. Refer to earlier turns in " +
    "plain prose (e.g. \"the previous model\") if you need to. This is a harness note, not a user request.\n" +
    "</model_attribution_reminder>";
  return customNote(REMINDER_CUSTOM_TYPE, text, timestamp);
}

/**
 * Transform a context message list: annotate every earlier assistant response,
 * keep the head note present, and append the identity reminder when the history
 * mixes models. Pure with respect to the input — input messages are never mutated.
 */
export function annotateContext(messages: MessageLike[], currentModel?: string): MessageLike[] {
  let annotated = 0;
  const out = messages.map((message) => {
    if (message.role !== "assistant") return message;
    // Also strip echo tags a model previously wrote into its own reply (request-local;
    // the stored session keeps the raw text, message_end prevents new echoes).
    const stripped = stripEchoedAttributionTag(message);
    const next = annotateAssistantMessage(stripped, currentModel);
    if (next !== message) annotated++;
    return next;
  });
  // Judged over the whole history (not just this pass) so an already-annotated
  // foreign response still triggers the identity reminder.
  const hasForeignModel =
    currentModel !== undefined &&
    messages.some((message) => {
      if (message.role !== "assistant") return false;
      const base = `${message.provider}/${message.model}`;
      return typeof message.provider === "string" && typeof message.model === "string" && base !== currentModel;
    });

  const seen = new Set(
    messages
      .filter((message) => message.role === "custom")
      .map((message) => message.customType as string),
  );
  const first = messages[0];
  const timestamp = typeof first?.timestamp === "number" ? first.timestamp : Date.now();

  // Keep the note even when nothing needed annotating in this pass but history has
  // annotations already (double load): presence is tracked via customType.
  const anyAnnotated = annotated > 0 || messages.some(
    (message) => message.role === "assistant" && Array.isArray(message.content) &&
      (message.content as ContentBlock[]).some(
        (block) => block.type === "text" && typeof block.text === "string" && block.text.startsWith(MARKER_PREFIX),
      ),
  );
  if (anyAnnotated && !seen.has(NOTE_CUSTOM_TYPE)) {
    out.unshift(buildNote(timestamp));
  }
  if (hasForeignModel && currentModel && !seen.has(REMINDER_CUSTOM_TYPE)) {
    out.push(buildReminder(currentModel, timestamp));
  }
  return out;
}

/**
 * Constant policy block appended to the leading system message of every request.
 * Model-independent (cache-stable): output-format rules live here because tail notes
 * alone proved insufficient — some models still echoed the tags into their replies.
 */
export function buildSystemPolicy(): string {
  return (
    `\n${POLICY_TAG}\n` +
    "This transcript may span multiple AI models. Assistant responses carry bracketed harness tags " +
    `such as ${MARKER_PREFIX}...] recording which model wrote them. Rules for your own output: ` +
    "never reproduce these tags or any similar bracketed attribution tags in your reply — the harness " +
    "inserts them automatically and echoing them corrupts the transcript. Never identify yourself with a " +
    "model named in an earlier tag; the harness reminder near the end of the transcript states which model " +
    "you are.\n" +
    "</model_attribution_policy>"
  );
}

/** Append the policy block to the leading system message (once). Pure w.r.t. input. */
export function applySystemPolicy(messages: MessageLike[]): MessageLike[] {
  const head = messages[0];
  if (!head || head.role !== "system") return messages;
  const content = head.content;
  const text =
    typeof content === "string"
      ? content
      : Array.isArray(content)
        ? (content as ContentBlock[]).map((block) => (typeof block.text === "string" ? block.text : "")).join("")
        : "";
  if (text.includes(POLICY_TAG)) return messages;
  const policy = buildSystemPolicy();
  const newHead =
    typeof content === "string"
      ? { ...head, content: content + policy }
      : { ...head, content: [...(content as ContentBlock[]), { type: "text", text: policy }] };
  return [newHead, ...messages.slice(1)];
}

/**
 * Strip leading echoed attribution tags from a finalized assistant message.
 * Only a tag run at the very start of the first text block is removed — inline
 * mentions (e.g. a user asking to quote a tag) are left alone. The block's
 * `textSignature` is dropped with the edit since it no longer matches the text.
 */
export function stripEchoedAttributionTag(message: MessageLike): MessageLike {
  const content = Array.isArray(message.content) ? (message.content as ContentBlock[]) : null;
  if (!content) return message;
  let index = 0;
  while (index < content.length && content[index]?.type === "thinking") index++;
  const block = content[index];
  if (!block || block.type !== "text" || typeof block.text !== "string") return message;
  const stripped = block.text.replace(ECHO_TAG_LEADING_RE, "");
  if (stripped === block.text || stripped.length === 0) return message;
  const { textSignature: _drop, ...rest } = block;
  const cleaned = { ...rest, text: stripped };
  return { ...message, content: [...content.slice(0, index), cleaned, ...content.slice(index + 1)] };
}

export default function modelAttributionExtension(pi: ExtensionAPI): void {
  pi.on("context", (event, ctx) => {
    const model = ctx.model;
    const currentModel = model ? `${model.provider}/${model.id}` : undefined;
    const messages = annotateContext(event.messages as unknown as MessageLike[], currentModel);
    return { messages: messages as unknown as typeof event.messages };
  });
  pi.on("context_with_system", (event) => {
    return { messages: applySystemPolicy(event.messages as unknown as MessageLike[]) as unknown as typeof event.messages };
  });
  pi.on("message_end", (event) => {
    const message = event.message;
    if (message.role !== "assistant") return;
    const cleaned = stripEchoedAttributionTag(message as unknown as MessageLike);
    if ((cleaned as unknown) !== (message as unknown)) return { message: cleaned as unknown as typeof message };
  });
}
